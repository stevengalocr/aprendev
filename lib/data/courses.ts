export function getCourseById(id: string): Course | undefined {
  return COURSES.find(c => c.id === id)
}

export function getLessonById(lessonId: string): { course: Course; lesson: import('@/types').Lesson } | undefined {
  for (const course of COURSES) {
    for (const unit of course.units) {
      for (const lesson of unit.lessons) {
        if (lesson.id === lessonId) return { course, lesson }
      }
    }
  }
  return undefined
}

export function getAllLessons(): Array<{ courseId: string; unitId: string; lesson: import('@/types').Lesson }> {
  const lessons: Array<{ courseId: string; unitId: string; lesson: import('@/types').Lesson }> = []
  for (const course of COURSES) {
    for (const unit of course.units) {
      for (const lesson of unit.lessons) {
        lessons.push({ courseId: course.id, unitId: unit.id, lesson })
      }
    }
  }
  return lessons
}

